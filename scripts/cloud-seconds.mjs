import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { podNeedsOf } from '../shared/modelFiles.js'
import { jobSecondsOf } from '../shared/gpuTiers.js'

// Writes shared/cloudSeconds.js: each bundled workflow's typical run time on the reference GPU,
// from its model files' `refSec`, as the Session tiers estimate it. The browser prices a Comfy Cloud
// run from this table without loading the graphs. cost-check fails when it is out of date.
export function cloudSecondsTable() {
  const out = {}
  for (const file of readdirSync('public/workflows').filter((f) => f.endsWith('.json')).sort()) {
    const graph = JSON.parse(readFileSync(`public/workflows/${file}`, 'utf8'))
    let seconds
    try { seconds = jobSecondsOf(podNeedsOf(graph)) } catch { seconds = null }
    if (seconds) out[file.slice(0, -5)] = seconds
  }
  return out
}

export const cloudSecondsSource = (table) => `// Generated by scripts/cloud-seconds.mjs. Do not edit by hand.
// Typical seconds per run on the reference GPU (RTX PRO 6000, the GPU Comfy Cloud bills), per bundled workflow.
export const cloudSeconds = ${JSON.stringify(table, null, 2).replace(/"([\w-]+)":/g, '$1:').replace(/"/g, "'")}
`

if (process.argv[1]?.endsWith('cloud-seconds.mjs')) {
  writeFileSync('shared/cloudSeconds.js', cloudSecondsSource(cloudSecondsTable()))
  console.log('Wrote shared/cloudSeconds.js')
}
